create or replace function public.grant_pro_subscription(
  p_telegram_id bigint,
  p_duration_months integer,
  p_source text,
  p_note text default null
) returns timestamptz
language plpgsql
security definer
set search_path = public
as $$
declare
  v_now timestamptz := now();
  v_expires timestamptz;
  v_duration_days integer;
begin
  if p_duration_months < 1 or p_duration_months > 36 then
    raise exception 'Subscription duration must be between 1 and 36 months';
  end if;
  v_duration_days := case when p_duration_months = 12 then 365 else p_duration_months * 30 end;

  insert into public.subscriptions as current_subscription
    (user_telegram_id, status, starts_at, expires_at, ends_at, source, note, updated_at)
  values
    (p_telegram_id, 'active', v_now, v_now + make_interval(days => v_duration_days),
     v_now + make_interval(days => v_duration_days), p_source, p_note, v_now)
  on conflict (user_telegram_id) do update set
    status = 'active',
    expires_at = greatest(current_subscription.expires_at, v_now) + make_interval(days => v_duration_days),
    ends_at = greatest(current_subscription.expires_at, v_now) + make_interval(days => v_duration_days),
    source = excluded.source,
    note = excluded.note,
    updated_at = v_now
  returning expires_at into v_expires;

  update public.users
  set is_pro = true, pro_status = 'pro', pro_until = v_expires, pro_expires = v_expires,
      pro_expires_at = v_expires
  where telegram_id = p_telegram_id;
  if not found then
    raise exception 'User not found';
  end if;

  return v_expires;
end;
$$;

create or replace function public.activate_paid_subscription(
  p_payment_id uuid,
  p_provider text,
  p_provider_transaction_id text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_payment public.payments%rowtype;
  v_expires timestamptz;
begin
  select * into v_payment
  from public.payments
  where id = p_payment_id
  for update;

  if not found then
    raise exception 'Payment not found';
  end if;

  if v_payment.provider <> p_provider then
    raise exception 'Payment provider mismatch';
  end if;

  if v_payment.status = 'paid' then
    select expires_at into v_expires from public.subscriptions
    where user_telegram_id = v_payment.user_telegram_id;
    return jsonb_build_object('ok', true, 'alreadyProcessed', true, 'expiresAt', v_expires);
  end if;

  if v_payment.status <> 'pending' then
    raise exception 'Payment is not pending';
  end if;
  if v_payment.expires_at <= now() then
    raise exception 'Payment has expired';
  end if;

  update public.payments
  set status = 'paid',
      provider_transaction_id = p_provider_transaction_id,
      paid_at = now()
  where id = p_payment_id;

  v_expires := public.grant_pro_subscription(
    v_payment.user_telegram_id,
    v_payment.duration_months,
    p_provider,
    'Payment ' || p_payment_id::text
  );

  return jsonb_build_object('ok', true, 'alreadyProcessed', false, 'expiresAt', v_expires);
end;
$$;

create or replace function public.approve_manual_payment(
  p_payment_id uuid,
  p_admin_telegram_id bigint
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_payment public.payments%rowtype;
  v_expires timestamptz;
begin
  select * into v_payment
  from public.payments
  where id = p_payment_id
  for update;

  if not found then
    raise exception 'Payment not found';
  end if;
  if v_payment.provider <> 'manual' then
    raise exception 'Payment is not manual';
  end if;
  if v_payment.status = 'paid' then
    select expires_at into v_expires from public.subscriptions
    where user_telegram_id = v_payment.user_telegram_id;
    return jsonb_build_object('ok', true, 'alreadyProcessed', true, 'expiresAt', v_expires);
  end if;
  if v_payment.status <> 'review' or not (v_payment.provider_data ? 'receipt_path') then
    raise exception 'Payment is not awaiting review';
  end if;

  update public.payments
  set status = 'paid',
      paid_at = now(),
      provider_transaction_id = coalesce(
        provider_transaction_id,
        'manual-' || p_payment_id::text
      ),
      provider_data = provider_data || jsonb_build_object(
        'reviewed_by', p_admin_telegram_id,
        'reviewed_at', now()
      )
  where id = p_payment_id;

  v_expires := public.grant_pro_subscription(
    v_payment.user_telegram_id,
    v_payment.duration_months,
    'manual_payment',
    'Payment ' || p_payment_id::text
  );
  return jsonb_build_object('ok', true, 'alreadyProcessed', false, 'expiresAt', v_expires);
end;
$$;

create or replace function public.consume_ai_request(p_telegram_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pro boolean;
  v_count integer;
  v_daily_limit integer := 5;
begin
  select exists (
    select 1
    from public.users u
    join public.subscriptions s on s.user_telegram_id = u.telegram_id
    where u.telegram_id = p_telegram_id
      and u.is_pro = true
      and coalesce(u.pro_expires_at, u.pro_until, u.pro_expires, 'infinity'::timestamptz) > now()
      and s.status = 'active'
      and s.expires_at > now()
  ) into v_pro;

  insert into public.ai_usage (user_telegram_id, usage_date, request_count)
  values (p_telegram_id, current_date, 0)
  on conflict (user_telegram_id, usage_date) do nothing;

  select request_count into v_count from public.ai_usage
  where user_telegram_id = p_telegram_id and usage_date = current_date
  for update;

  if not v_pro and v_count >= v_daily_limit then
    return jsonb_build_object('allowed', false, 'isPro', false, 'used', v_count, 'limit', v_daily_limit);
  end if;

  update public.ai_usage
  set request_count = request_count + 1
  where user_telegram_id = p_telegram_id and usage_date = current_date
  returning request_count into v_count;

  return jsonb_build_object(
    'allowed', true,
    'isPro', v_pro,
    'used', v_count,
    'limit', case when v_pro then null else v_daily_limit end
  );
end;
$$;

create or replace function public.cancel_pending_payment(
  p_provider_transaction_id text,
  p_reason integer default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_payment public.payments%rowtype;
begin
  select * into v_payment
  from public.payments
  where provider = 'payme'
    and provider_transaction_id = p_provider_transaction_id
  for update;

  if not found then
    raise exception 'Transaction not found';
  end if;

  if v_payment.status = 'paid' then
    return jsonb_build_object('canceled', false, 'paid', true);
  end if;

  if v_payment.status = 'canceled' then
    return jsonb_build_object('canceled', true, 'alreadyCanceled', true);
  end if;

  update public.payments
  set status = 'canceled',
      provider_data = provider_data || jsonb_build_object(
        'cancel_reason', p_reason,
        'payme_cancel_time', floor(extract(epoch from now()) * 1000)::bigint
      )
  where id = v_payment.id;

  return jsonb_build_object(
    'canceled', true,
    'alreadyCanceled', false,
    'cancelTime', floor(extract(epoch from now()) * 1000)::bigint
  );
end;
$$;

create or replace function public.revoke_pro_subscription(p_telegram_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.subscriptions
  set status = 'revoked', expires_at = now(), ends_at = now(), updated_at = now()
  where user_telegram_id = p_telegram_id;
  update public.users
  set is_pro = false, pro_status = 'free', pro_until = null, pro_expires = null,
      pro_expires_at = null
  where telegram_id = p_telegram_id;
  return found;
end;
$$;

create or replace function public.subscription_revenue()
returns jsonb
language sql
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'totalUzs', coalesce(sum(amount_uzs), 0),
    'paymentCount', count(*)
  )
  from public.payments
  where status = 'paid';
$$;

